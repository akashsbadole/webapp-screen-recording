import jsPDF from "jspdf";
import { Annotation } from "@/components/advanced-annotation-canvas";

interface PDFOptions {
  title?: string;
  author?: string;
  includeAnnotations?: boolean;
  includeSteps?: boolean;
  pageSize?: "a4" | "letter" | "legal";
}

export class PDFGenerator {
  private pdf: jsPDF;
  private options: PDFOptions;

  constructor(options: PDFOptions = {}) {
    this.options = {
      title: "Media Recording Annotations",
      author: "Screen Recording Web App",
      includeAnnotations: true,
      includeSteps: true,
      pageSize: "a4",
      ...options,
    };

    this.pdf = new jsPDF({
      orientation: "portrait",
      unit: "mm",
      format: this.options.pageSize,
    });

    // Set document properties
    this.pdf.setProperties({
      title: this.options.title,
      subject: "Recording Annotations and Guide",
      author: this.options.author,
      creator: "Screen Recording Web App",
      producer: "Screen Recording Web App",
    });
  }

  async generatePDF(
    mediaUrl: string,
    annotations: Annotation[],
    mediaType: "video" | "image" = "image"
  ): Promise<Blob> {
    try {
      // Add title page
      this.addTitlePage();

      // Add media preview
      await this.addMediaPreview(mediaUrl, mediaType);

      // Add annotations summary
      if (this.options.includeAnnotations && annotations.length > 0) {
        this.addAnnotationsSummary(annotations);
      }

      // Add detailed annotations
      if (this.options.includeAnnotations && annotations.length > 0) {
        this.addDetailedAnnotations(annotations);
      }

      // Add guide steps if available
      if (this.options.includeSteps) {
        this.addGuideSteps(annotations);
      }

      return this.pdf.output("blob");
    } catch (error) {
      console.error("Error generating PDF:", error);
      throw new Error("Failed to generate PDF");
    }
  }

  private addTitlePage(): void {
    const pageWidth = this.pdf.internal.pageSize.getWidth();
    const pageHeight = this.pdf.internal.pageSize.getHeight();

    // Add background
    this.pdf.setFillColor(245, 245, 245);
    this.pdf.rect(0, 0, pageWidth, pageHeight, "F");

    // Add title
    this.pdf.setFontSize(24);
    this.pdf.setTextColor(33, 37, 41);
    const title = this.options.title || "Media Recording Annotations";
    const titleWidth = this.pdf.getTextWidth(title);
    this.pdf.text(title, (pageWidth - titleWidth) / 2, 60);

    // Add subtitle
    this.pdf.setFontSize(14);
    this.pdf.setTextColor(108, 117, 125);
    const subtitle = "Professional Recording Analysis and Documentation";
    const subtitleWidth = this.pdf.getTextWidth(subtitle);
    this.pdf.text(subtitle, (pageWidth - subtitleWidth) / 2, 80);

    // Add author and date
    this.pdf.setFontSize(10);
    this.pdf.setTextColor(108, 117, 125);
    const author = `Generated by: ${this.options.author}`;
    const date = `Date: ${new Date().toLocaleDateString()}`;
    this.pdf.text(author, 20, pageHeight - 40);
    this.pdf.text(date, 20, pageHeight - 30);

    // Add decorative elements
    this.pdf.setDrawColor(52, 144, 220);
    this.pdf.setLineWidth(2);
    this.pdf.line(20, 100, pageWidth - 20, 100);
  }

  private async addMediaPreview(
    mediaUrl: string,
    mediaType: "video" | "image"
  ): Promise<void> {
    this.pdf.addPage();

    const pageWidth = this.pdf.internal.pageSize.getWidth();
    const pageHeight = this.pdf.internal.pageSize.getHeight();

    // Add section title
    this.pdf.setFontSize(18);
    this.pdf.setTextColor(33, 37, 41);
    this.pdf.text("Media Preview", 20, 30);

    // Add media type indicator
    this.pdf.setFontSize(12);
    this.pdf.setTextColor(108, 117, 125);
    this.pdf.text(`Type: ${mediaType.toUpperCase()}`, 20, 45);

    // Add placeholder for media (in a real implementation, you'd capture the actual frame)
    this.pdf.setDrawColor(200, 200, 200);
    this.pdf.setFillColor(240, 240, 240);
    this.pdf.rect(20, 60, pageWidth - 40, 120, "FD");

    this.pdf.setFontSize(14);
    this.pdf.setTextColor(108, 117, 125);
    const placeholderText = "Media Preview";
    const textWidth = this.pdf.getTextWidth(placeholderText);
    this.pdf.text(placeholderText, (pageWidth - textWidth) / 2, 125);
  }

  private addAnnotationsSummary(annotations: Annotation[]): void {
    this.pdf.addPage();

    const pageWidth = this.pdf.internal.pageSize.getWidth();

    // Add section title
    this.pdf.setFontSize(18);
    this.pdf.setTextColor(33, 37, 41);
    this.pdf.text("Annotations Summary", 20, 30);

    // Summary statistics
    const summary = this.getAnnotationSummary(annotations);

    this.pdf.setFontSize(12);
    this.pdf.setTextColor(33, 37, 41);

    let yPos = 50;
    this.pdf.text(`Total Annotations: ${summary.total}`, 20, yPos);
    yPos += 10;
    this.pdf.text(`Text Annotations: ${summary.text}`, 20, yPos);
    yPos += 10;
    this.pdf.text(`Shapes: ${summary.shapes}`, 20, yPos);
    yPos += 10;
    this.pdf.text(`Arrows: ${summary.arrows}`, 20, yPos);
    yPos += 10;
    this.pdf.text(`Drawings: ${summary.drawings}`, 20, yPos);
    yPos += 10;
    this.pdf.text(`Highlights: ${summary.highlights}`, 20, yPos);
    yPos += 10;
    this.pdf.text(`Stamps: ${summary.stamps}`, 20, yPos);

    // Add simple bar chart
    yPos += 20;
    this.pdf.setFontSize(14);
    this.pdf.text("Annotation Distribution", 20, yPos);
    yPos += 10;

    const chartData = [
      { label: "Text", value: summary.text, color: [255, 99, 132] },
      { label: "Shapes", value: summary.shapes, color: [54, 162, 235] },
      { label: "Arrows", value: summary.arrows, color: [255, 205, 86] },
      { label: "Drawings", value: summary.drawings, color: [75, 192, 192] },
      {
        label: "Highlights",
        value: summary.highlights,
        color: [153, 102, 255],
      },
      { label: "Stamps", value: summary.stamps, color: [255, 159, 64] },
    ];

    this.drawBarChart(chartData, 20, yPos, pageWidth - 40, 60);
  }

  private addDetailedAnnotations(annotations: Annotation[]): void {
    this.pdf.addPage();

    const pageWidth = this.pdf.internal.pageSize.getWidth();
    const pageHeight = this.pdf.internal.pageSize.getHeight();

    // Add section title
    this.pdf.setFontSize(18);
    this.pdf.setTextColor(33, 37, 41);
    this.pdf.text("Detailed Annotations", 20, 30);

    let yPos = 50;
    const lineHeight = 8;

    annotations.forEach((annotation, index) => {
      // Check if we need a new page
      if (yPos > pageHeight - 30) {
        this.pdf.addPage();
        yPos = 30;
      }

      // Annotation number and type
      this.pdf.setFontSize(12);
      this.pdf.setTextColor(33, 37, 41);
      this.pdf.text(`${index + 1}. ${annotation.type.toUpperCase()}`, 20, yPos);
      yPos += lineHeight;

      // Annotation details
      this.pdf.setFontSize(10);
      this.pdf.setTextColor(108, 117, 125);

      if (annotation.text) {
        this.pdf.text(`Text: "${annotation.text}"`, 25, yPos);
        yPos += lineHeight;
      }

      if (annotation.stampType) {
        this.pdf.text(`Stamp: ${annotation.stampType}`, 25, yPos);
        yPos += lineHeight;
      }

      this.pdf.text(
        `Position: (${Math.round(annotation.x)}, ${Math.round(annotation.y)})`,
        25,
        yPos
      );
      yPos += lineHeight;

      if (annotation.width && annotation.height) {
        this.pdf.text(
          `Size: ${Math.round(annotation.width)} × ${Math.round(
            annotation.height
          )}`,
          25,
          yPos
        );
        yPos += lineHeight;
      }

      this.pdf.text(`Color: ${annotation.color}`, 25, yPos);
      yPos += lineHeight;

      if (annotation.layer) {
        this.pdf.text(`Layer: ${annotation.layer}`, 25, yPos);
        yPos += lineHeight;
      }

      // Add separator
      yPos += 5;
      this.pdf.setDrawColor(200, 200, 200);
      this.pdf.setLineWidth(0.5);
      this.pdf.line(20, yPos, pageWidth - 20, yPos);
      yPos += 10;
    });
  }

  private addGuideSteps(annotations: Annotation[]): void {
    // Extract guide steps from annotations (simplified approach)
    const guideAnnotations = annotations.filter(
      (ann) => ann.type === "text" && ann.text?.match(/^\d+\./)
    );

    if (guideAnnotations.length === 0) return;

    this.pdf.addPage();

    const pageWidth = this.pdf.internal.pageSize.getWidth();
    const pageHeight = this.pdf.internal.pageSize.getHeight();

    // Add section title
    this.pdf.setFontSize(18);
    this.pdf.setTextColor(33, 37, 41);
    this.pdf.text("Step-by-Step Guide", 20, 30);

    let yPos = 50;
    const lineHeight = 8;

    guideAnnotations.forEach((annotation, index) => {
      // Check if we need a new page
      if (yPos > pageHeight - 30) {
        this.pdf.addPage();
        yPos = 30;
      }

      // Step number
      this.pdf.setFontSize(14);
      this.pdf.setTextColor(52, 144, 220);
      this.pdf.text(`Step ${index + 1}`, 20, yPos);
      yPos += lineHeight;

      // Step description
      if (annotation.text) {
        this.pdf.setFontSize(12);
        this.pdf.setTextColor(33, 37, 41);
        const description = annotation.text.replace(/^\d+\.\s*/, "");
        const lines = this.pdf.splitTextToSize(description, pageWidth - 40);

        lines.forEach((line: string) => {
          this.pdf.text(line, 25, yPos);
          yPos += lineHeight;
        });
      }

      // Add position reference
      this.pdf.setFontSize(10);
      this.pdf.setTextColor(108, 117, 125);
      this.pdf.text(
        `Reference: (${Math.round(annotation.x)}, ${Math.round(annotation.y)})`,
        25,
        yPos
      );
      yPos += lineHeight + 5;
    });
  }

  private getAnnotationSummary(annotations: Annotation[]) {
    return {
      total: annotations.length,
      text: annotations.filter((a) => a.type === "text").length,
      shapes: annotations.filter(
        (a) => a.type === "rectangle" || a.type === "circle"
      ).length,
      arrows: annotations.filter((a) => a.type === "arrow").length,
      drawings: annotations.filter((a) => a.type === "pen").length,
      highlights: annotations.filter((a) => a.type === "highlighter").length,
      stamps: annotations.filter((a) => a.type === "stamp").length,
    };
  }

  private drawBarChart(
    data: { label: string; value: number; color: number[] }[],
    x: number,
    y: number,
    width: number,
    height: number
  ): void {
    const maxValue = Math.max(...data.map((d) => d.value));
    const barWidth = (width / data.length) * 0.8;
    const barSpacing = (width / data.length) * 0.2;

    data.forEach((item, index) => {
      const barHeight = maxValue > 0 ? (item.value / maxValue) * height : 0;
      const barX = x + index * (barWidth + barSpacing);
      const barY = y + height - barHeight;

      // Draw bar
      this.pdf.setFillColor(...item.color);
      this.pdf.rect(barX, barY, barWidth, barHeight, "F");

      // Draw label
      this.pdf.setFontSize(8);
      this.pdf.setTextColor(33, 37, 41);
      this.pdf.text(item.label, barX + barWidth / 2, y + height + 5, {
        align: "center",
      });

      // Draw value
      if (item.value > 0) {
        this.pdf.text(item.value.toString(), barX + barWidth / 2, barY - 2, {
          align: "center",
        });
      }
    });
  }
}

export const generateAnnotationPDF = async (
  mediaUrl: string,
  annotations: Annotation[],
  options?: PDFOptions
): Promise<Blob> => {
  const generator = new PDFGenerator(options);
  return generator.generatePDF(mediaUrl, annotations);
};
